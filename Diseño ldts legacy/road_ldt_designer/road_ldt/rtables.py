_SCALE = 1.0 / 10_000.0


def _bracket(values: tuple[float, ...], value: float) -> tuple[int, int, float]:
    value = min(max(float(value), values[0]), values[-1])
    lower = bisect.bisect_right(values, value) - 1
    lower = max(0, min(lower, len(values) - 2))
    upper = lower + 1
    span = values[upper] - values[lower]
    weight = (value - values[lower]) / span if span > 0 else 0.0
    return lower, upper, weight


def r_value(table_name: str, beta_deg: float, tan_epsilon: float) -> float:
    """Bilinear interpolation of reduced luminance coefficient r [sr⁻¹]."""

    name = str(table_name).upper()
    if name not in TABLES_RAW:
        raise ValueError(f"r-table no disponible: {table_name}")
    table = TABLES_RAW[name]
    bi0, bi1, wb = _bracket(BETA_COLS, beta_deg)
    ti0, ti1, wt = _bracket(TAN_EPSILON_ROWS, tan_epsilon)

    r00 = table[ti0][bi0]
    r01 = table[ti0][bi1]
    r10 = table[ti1][bi0]
    r11 = table[ti1][bi1]
    interpolated_raw = (
        (1.0 - wt) * ((1.0 - wb) * r00 + wb * r01)
        + wt * ((1.0 - wb) * r10 + wb * r11)
    )
    return float(interpolated_raw) * _SCALE


def list_tables() -> tuple[str, ...]:
    return tuple(TABLES_RAW)
