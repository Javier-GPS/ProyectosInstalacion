def r_value(table_name: str, beta_deg: float, tan_gamma: float) -> float:
    """
    Bilinear interpolation of reduced luminance coefficient r [sr⁻¹].

    Parameters
    ----------
    table_name : str
        One of 'C1','C2','R1'..'R4','N1'..'N4'
    beta_deg   : float
        Angle of deviation β in degrees  [0 … 180]
    tan_gamma  : float
        tan of the angle of incidence γ  [0 … 4]

    Returns
    -------
    float
        r [sr⁻¹]  (physical value)
    """
    table = TABLES[table_name]

    # Clamp to table domain
    beta_deg  = max(0.0, min(float(beta_deg),  180.0))
    tan_gamma = max(0.0, min(float(tan_gamma),   4.0))

    # Find bounding indices in β axis
    bi = np.searchsorted(_beta_arr, beta_deg, side="right") - 1
    bi = int(np.clip(bi, 0, len(_beta_arr) - 2))

    # Find bounding indices in tan(γ) axis
    ti = np.searchsorted(_tg_arr, tan_gamma, side="right") - 1
    ti = int(np.clip(ti, 0, len(_tg_arr) - 2))

    # Interpolation weights
    b0, b1 = _beta_arr[bi], _beta_arr[bi + 1]
    t0, t1 = _tg_arr[ti],   _tg_arr[ti + 1]

    wb = (beta_deg  - b0) / (b1 - b0) if b1 > b0 else 0.0
    wt = (tan_gamma - t0) / (t1 - t0) if t1 > t0 else 0.0

    r00 = table[ti,     bi    ]
    r10 = table[ti + 1, bi    ]
    r01 = table[ti,     bi + 1]
    r11 = table[ti + 1, bi + 1]

    # Bilinear
    return float((1 - wt) * ((1 - wb) * r00 + wb * r01)
                 +     wt  * ((1 - wb) * r10 + wb * r11))


def r_value_batch(table_name: str, beta_deg, tan_gamma):
    """
    Vectorized bilinear interpolation of r [sr⁻¹] — same table lookup as
    r_value() but beta_deg/tan_gamma may be numpy arrays (broadcastable).
    Returns an ndarray of the broadcast shape.
    """
    table = TABLES[table_name]

    beta_deg  = np.clip(np.asarray(beta_deg,  dtype=float), 0.0, 180.0)
    tan_gamma = np.clip(np.asarray(tan_gamma, dtype=float),   0.0, 4.0)

    bi = np.searchsorted(_beta_arr, beta_deg, side="right") - 1
    bi = np.clip(bi, 0, len(_beta_arr) - 2)
    ti = np.searchsorted(_tg_arr, tan_gamma, side="right") - 1
    ti = np.clip(ti, 0, len(_tg_arr) - 2)

    b0, b1 = _beta_arr[bi], _beta_arr[bi + 1]
    t0, t1 = _tg_arr[ti],   _tg_arr[ti + 1]

    db = b1 - b0
    wb = np.where(db > 0, (beta_deg - b0) / np.where(db > 0, db, 1.0), 0.0)
    dt = t1 - t0
    wt = np.where(dt > 0, (tan_gamma - t0) / np.where(dt > 0, dt, 1.0), 0.0)

    r00 = table[ti,     bi    ]
    r10 = table[ti + 1, bi    ]
    r01 = table[ti,     bi + 1]
    r11 = table[ti + 1, bi + 1]

    return (1 - wt) * ((1 - wb) * r00 + wb * r01) + wt * ((1 - wb) * r10 + wb * r11)


def list_tables() -> list[str]:
    return list(TABLES.keys())
