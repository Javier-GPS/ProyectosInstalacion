export function rValue(tanGamma: number, betaDeg: number): number {
  const tg = Math.max(0, Math.min(12, tanGamma));
  let bd = Math.abs(betaDeg) % 360;
  if (bd > 180) bd = 360 - bd;

  let i = TANG.findIndex(t => t > tg) - 1;
  i = Math.max(0, Math.min(i, TANG.length - 2));
  let j = BETAS.findIndex(b => b > bd) - 1;
  j = Math.max(0, Math.min(j, BETAS.length - 2));

  const v00 = R3_TABLE[i][j];
  const v01 = R3_TABLE[i][j + 1];
  const v10 = R3_TABLE[i + 1][j];
  const v11 = R3_TABLE[i + 1][j + 1];
  if (v00 === 0 || v01 === 0 || v10 === 0 || v11 === 0) return 0;

  const t = TANG[i + 1] !== TANG[i] ? (tg - TANG[i]) / (TANG[i + 1] - TANG[i]) : 0;
  const u = BETAS[j + 1] !== BETAS[j] ? (bd - BETAS[j]) / (BETAS[j + 1] - BETAS[j]) : 0;
  const v = (1 - t) * (1 - u) * v00 + (1 - t) * u * v01 + t * (1 - u) * v10 + t * u * v11;
  return v / 10000;
}
